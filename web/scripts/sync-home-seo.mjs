/** Explicit source refresh; normal builds validate rather than edit tracked HTML. */
import { readFile, writeFile } from 'node:fs/promises';
import { demoPage, site } from '../src/lib/seo.mjs';
import { staticHead } from '../src/lib/static-head.mjs';
const file = new URL('../public/index.html', import.meta.url);
const html = await readFile(file, 'utf8');
const block = `<!-- SEO: generated by npm run seo:refresh -->\n${staticHead({ ...site, path: '/' })}\n<!-- /SEO -->`;
const pattern = /<!-- SEO: generated by npm run seo:refresh -->[\s\S]*?<!-- \/SEO -->/;
if (!pattern.test(html)) throw new Error('Homepage SEO markers are missing');
await writeFile(file, html.replace(pattern, block));
console.log('Homepage metadata refreshed');
const demoFile = new URL('../public/demo/index.html', import.meta.url);
const demoHtml = await readFile(demoFile, 'utf8');
if (!pattern.test(demoHtml)) throw new Error('Demo SEO markers are missing');
await writeFile(demoFile, demoHtml.replace(pattern, `<!-- SEO: generated by npm run seo:refresh -->\n${staticHead(demoPage)}\n<!-- /SEO -->`));
console.log('Demo metadata refreshed');
